T = {k: [] for k in COLS}


def add(table, **kw):
    cols = COLS[table].split(",")
    bad = set(kw) - set(cols)
    assert not bad, (table, bad)
    T[table].append({c: NFC(str(kw.get(c, ""))) for c in cols})


